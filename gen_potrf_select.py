#!/usr/bin/env python3
"""Generates potrf_select.mojo from the tuning runs in tune-potrf/ (see
tune-potrf.sh): for each backend and each n of the grid the fastest
configuration (algorithm, threads, nb).  A configuration with fewer
threads is preferred if it is within 3% of the fastest.  Between grid
points the threshold is the midpoint.  Without tuning data a fixed fallback
is generated.

Files of a backend directory:
    t<T>-nb<NB>.txt   tiles and tasks, T threads, tile size NB
    pk.txt            pack once (one thread)
    pk3.txt           pack once with lookahead (two threads)
"""

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent
TUNE = ROOT / "tune-potrf"
# backend directory -> ACC parameter of potrf (SME2 micro kernel)
BACKENDS = {"sme": 0, "accelerate-blas": 1}
TOLERANCE = 0.03
ALG = {"tiles": 0, "pk": 1, "pk3": 2}


def read(path):
    rows = {}
    for line in path.read_text().splitlines():
        f = line.split()
        if not f or line.startswith("#"):
            continue
        if f[3] != "ok":
            raise SystemExit(f"{path}: check failed for n = {f[0]}")
        rows[int(f[0])] = float(f[2])
    return rows


def configs(d):
    """{(algorithm, threads, nb): {n: GFLOP/s}}"""
    runs = {}
    for p in sorted(d.glob("*.txt")):
        m = re.fullmatch(r"t(\d+)-nb(\d+)", p.stem)
        if m:
            runs[(ALG["tiles"], int(m[1]), int(m[2]))] = read(p)
        elif p.stem == "pk":
            runs[(ALG["pk"], 1, 0)] = read(p)
        elif p.stem == "pk3":
            runs[(ALG["pk3"], 2, 0)] = read(p)
    return runs


def best_configs(d):
    runs = configs(d)
    sizes = sorted(set.intersection(*(set(r) for r in runs.values())))
    best = []
    for n in sizes:
        top = max(r[n] for r in runs.values())
        ok = [(c, r[n]) for c, r in runs.items()
              if r[n] >= (1 - TOLERANCE) * top]
        c, g = min(ok, key=lambda x: (x[0][1], -x[1]))
        best.append((n, c, g))
    return best


def merge(best):
    """Ranges [lo, hi] of n with the same configuration."""
    ranges = []
    for i, (n, c, _) in enumerate(best):
        hi = (n + best[i + 1][0]) // 2 if i + 1 < len(best) else None
        if ranges and ranges[-1][2] == c:
            ranges[-1] = (ranges[-1][0], hi, c)
        else:
            ranges.append((0 if not ranges else ranges[-1][1] + 1, hi, c))
    return ranges


NAME = {0: "tiles", 1: "pk", 2: "pk3"}


def main():
    out = ["# Generated by gen_potrf_select.py from the tuning runs in",
           "# tune-potrf/ (sh tune-potrf.sh).  Do not edit.",
           "#",
           "# potrf_select[SME, ACC](n) -> (algorithm, nthreads, nb): the",
           "# configuration potrf uses for nthreads = 0.  Algorithm: 0 tiles",
           "# and tasks, 1 pack once (potrf_pk), 2 pack once with lookahead",
           "# (potrf_pk3).", "", "",
           "def potrf_select[SME: Bool, ACC: Int](n: Int) -> Tuple[Int, Int, "
           "Int]:"]
    summary = ["Fastest configuration per n; a configuration with fewer "
               f"threads is taken if it is within {TOLERANCE:.0%} of the "
               "fastest.", ""]
    tuned = False
    for name, acc in BACKENDS.items():
        d = TUNE / name
        if not d.is_dir() or not list(d.glob("*.txt")):
            continue
        tuned = True
        best = best_configs(d)
        out.append(f"    comptime if SME and ACC == {acc}:")
        for lo, hi, (a, t, nb) in merge(best):
            note = f"  # {NAME[a]}, n >= {lo}"
            if hi is None:
                out.append(f"        return ({a}, {t}, {nb}){note}")
            else:
                out.append(f"        if n <= {hi}:{note}")
                out.append(f"            return ({a}, {t}, {nb})")
        summary += [f"### {name}", "",
                    "| n | algorithm | threads | nb | GFLOP/s |",
                    "|---:|---|---:|---:|---:|"]
        summary += [f"| {n} | {NAME[a]} | {t} | {nb or ''} | {g:.0f} |"
                    for n, (a, t, nb), g in best]
        summary.append("")
    out += ["    # not tuned (other backends, or no tuning data)",
            "    return (0, 1, 4096) if n <= 1000 else (0, 4, 256)", ""]
    (ROOT / "potrf_select.mojo").write_text("\n".join(out))
    if tuned:
        (TUNE / "summary.md").write_text("\n".join(summary))
        print("\n".join(summary))


if __name__ == "__main__":
    main()
